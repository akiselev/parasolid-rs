//! `PK_ERROR_*` numeric code table — **[probed]**, recovered from the DLL.
//!
//! Every constant here was read out of `pskernel.dll` (V37.01.243) rather than
//! transcribed from documentation. Method (`crates/parasolid-test/src/bin/
//! error_table_probe.rs`): `PK_ERROR_raise` accepts a `PK_ERROR_sf_t` carrying a
//! bare numeric code, and the kernel **canonicalizes** it — `PK_ERROR_ask_last`
//! then reports the official `code_token` string for that code. Sweeping
//! 0..=9000 recovered 631 codes.
//!
//! # Coverage limits
//!
//! The sweep covered 0..=9000. One code above that range exists and is defined
//! separately below: `PK_ERROR_invalid_object` = 9999. Codes **15000..=15999**
//! have no individual names at all — `PKU_error_code_mnemonic` short-circuits
//! the whole band to the literal string `"$PF_ERROR"`.
//!
//! A static reconstruction of the kernel's complete code→token map (the switch
//! in `PKU_error_code_mnemonic` plus the `KI_*` mnemonic array) was diffed
//! against this file: **0 value mismatches, 0 spurious entries**, and the one
//! missing code noted above.
//!
//! Cross-validated against real (non-raised) errors: `distance_le_0` = 15 from a
//! negative block dimension, `not_an_entity` = 22 from a bogus tag,
//! `o_t_version_unknown` = 5022 from a bad option version, `field_of_wrong_type`
//! = 5014 and `o_t_version_incorrect` = 5043 from earlier boolean work, and
//! `not_general` = 5064 from `PK_VERTEX_delete_acorn`. The raised-code path and
//! the real-error path agree on all six.
//!
//! # Why this file exists
//!
//! The previous hand-written table was **entirely wrong** — all 22 constants
//! that could be checked disagreed with the kernel, and two pairs collided
//! (`system_error`/`modeller_not_started` both 2; `not_implemented`/
//! `cant_heal_wound` both 600). The damage was not theoretical: `pk_check`
//! treated code 7 as a success synonym for `PK_ERROR_cant_be_aborted` (really
//! 965), silently swallowing every `PK_ERROR_has_no_name` (really 7), and
//! `PsError::from_code` dispatched `NotAnEntity` on 504, a code the kernel never
//! emits.
//!
//! # What this table does *not* carry
//!
//! Severity. The probe supplies severity on the raised struct and the kernel
//! echoes it back, so the sweep proves nothing about it. Severity must be read
//! from `PK_ERROR_sf_t.severity` (offset 68) on a real error — see
//! `PK_ERROR_severity_t`. Every real error observed so far reports mild (1).

